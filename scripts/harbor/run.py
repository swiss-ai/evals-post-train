def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--benchmark", required=True, help=f"Comma-separated: {', '.join(BENCHMARKS)}.")
    p.add_argument("--model", help="Served model name at --api-base-url.")
    p.add_argument("--api-base-url", help="OpenAI-compatible endpoint (/v1 root).")
    p.add_argument("--gold", action="store_true", help="Harbor's oracle agent instead of a model.")
    p.add_argument("--agent", default="terminus-2", help="Harbor agent (default: terminus-2).")
    p.add_argument("--work-dir", required=True)
    p.add_argument("--sandbox", choices=tuple(ENVIRONMENTS), required=True)
    p.add_argument("--limit", type=int, help="First n tasks per benchmark.")
    p.add_argument("--task", action="append", default=[], help="Task name (glob) to include; repeatable.")
    p.add_argument("--max-concurrency", type=int, default=4)
    p.add_argument("--attempts", type=int, default=1, help="Attempts per task (Harbor's -k).")
    p.add_argument("--timeout-multiplier", type=float, default=1.0)
    p.add_argument("--agent-kwarg", action="append", default=[], help="Harbor --ak key=value; repeatable.")
    for flag in ("temperature", "top-p", "top-k", "min-p", "repetition-penalty"):
        p.add_argument("--" + flag, default=None, help="Sampling setting of the model, or 'none' to leave it out.")
    p.add_argument("--sampling-profile", default=None, help="Profile of the sampling config (e.g. greedy).")
    p.add_argument("--sampling-config", default=None, help="Sampling config (default: configs/sampling_defaults.json).")
    p.add_argument("--enable-thinking", dest="enable_thinking", action="store_true", default=None,
                   help="Switch the model's chat-template thinking on (terminus-2 only).")
    p.add_argument("--no-enable-thinking", dest="enable_thinking", action="store_false",
                   help="Switch the model's chat-template thinking off (terminus-2 only).")
    p.add_argument("--reasoning-effort", default=None, help="Reasoning effort of the model (terminus-2 only).")
    p.add_argument(
        "--agent-network",
        choices=("allowlist", "public"),
        default="allowlist",
        help="SWE-bench Verified/Pro: the agent phase reaches only package indexes (allowlist, "
        "the default; scripts/common/swe_bench_egress.py) or the whole internet (public, as the "
        "published tasks have it). Other benchmarks keep their own policies.",
    )
    args = p.parse_args(argv)
    names = [n.strip() for n in args.benchmark.split(",") if n.strip()]
    unknown = [n for n in names if n not in BENCHMARKS]
    if unknown:
        p.error(f"unknown --benchmark {', '.join(unknown)} (choose from {', '.join(BENCHMARKS)})")
    if args.sandbox == "k8s":
        for name in names:
            if BENCHMARKS[name].get("not_on_k8s"):
                p.error(f"{name} needs --sandbox docker or opensandbox: {BENCHMARKS[name]['not_on_k8s']}")
    if not args.gold:
        # --gold checks the environments and tests; it needs no judges.
        for name in names:
            keys = BENCHMARKS[name].get("grader_keys", ())
            if keys and not any(os.environ.get(key) for key in keys):
                p.error(
                    f"{name}'s LLM graders need {' or '.join(keys)}: without one, the verifier "
                    "skips them and scores the tests alone, which is not the benchmark's score"
                )
    if args.sandbox == "opensandbox" and not os.environ.get("OPENSANDBOX_API_KEY"):
        p.error("--sandbox opensandbox needs OPENSANDBOX_API_KEY")
    if not args.gold and not (args.model and args.api_base_url):
        p.error("--model and --api-base-url are required (or --gold)")
    args.benchmarks = names
    return args


def harbor_bin() -> str:
    return str(Path(sys.executable).parent / "harbor")


def adapter_command(adapter: str) -> List[str]:
    root = os.environ.get("HARBOR_ADAPTERS_ROOT")
    if root:
        installed = Path(root) / adapter / "bin" / adapter
        if installed.is_file():
            return [str(installed)]
    if os.environ.get("EVAL_PREBUILT_ENV") == "1":
        raise SystemExit(
            f"EVAL_PREBUILT_ENV=1 but the {adapter} adapter is not installed under HARBOR_ADAPTERS_ROOT "
            f"({root or 'unset'}), and a prebuilt image installs nothing at run time."
        )
    source = f"git+https://github.com/harbor-framework/harbor@v{HARBOR_VERSION}#subdirectory=adapters/{adapter}"
    return ["uvx", "--from", source, adapter]


def download_dataset(repo: str, revision: str) -> Path:
    """The dataset's JSONL files at a pinned revision (<language>/<org>__<repo>_dataset.jsonl, the
    layout the adapter's --dataset-path expects), in the Hugging Face cache."""
    from huggingface_hub import snapshot_download

    return Path(snapshot_download(repo_id=repo, repo_type="dataset", revision=revision, allow_patterns=["*.jsonl"]))


def generate_adapter_tasks(
    adapter: str, work_dir: Path, limit: Optional[int], tasks: List[str], dataset: Optional[Path] = None
) -> Path:
    """Tasks for a benchmark that is an adapter, not a published dataset: Harbor's adapter at
    the pinned Harbor version, installed under HARBOR_ADAPTERS_ROOT (the prebuilt image) or
    else run through uvx (its own dependencies, cached by uv)."""
    out = work_dir / "tasks" / adapter
    cmd = adapter_command(adapter) + ["--output-dir", str(out)]
    if dataset is not None:
        cmd += ["--dataset-path", str(dataset)]
    if tasks:
        cmd += ["--no-all", "--task-ids", *tasks]
    elif limit:
        cmd += ["--limit", str(limit)]
    print("Generating tasks:", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
    return out


def patched_tasks(dataset: str, patch: Callable[[Path], None], out: Path) -> Path:
    """A registry dataset downloaded afresh to <out>/<dataset name>/ and patched (see
    scripts/harbor/task_patches.py)."""
    cmd = [harbor_bin(), "download", dataset, "-o", str(out), "--export", "--overwrite"]
    print("Downloading tasks:", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
    (tasks,) = [p for p in out.iterdir() if p.is_dir()]
    patch(tasks)
    return tasks


def task_patches(args: argparse.Namespace, name: str) -> List[Callable[[Path], None]]:
    """The patches a benchmark's downloaded tasks get before the run (scripts/harbor/task_patches.py)."""
    spec = BENCHMARKS[name]
    patches = [spec["patch_tasks"]] if "patch_tasks" in spec else []
    if spec.get("agent_allowlist") and args.agent_network == "allowlist":
        patches.append(patch_swe_bench_agent_egress)
    return patches


def agent_kwargs(args: argparse.Namespace) -> List[str]:
    """The --ak entries: the user's own, plus the model's sampling and thinking settings.

    terminus-2 reads `temperature` and `llm_kwargs` (extra LLM call kwargs); everything but the
    temperature goes in llm_kwargs' extra_body, which the OpenAI-compatible server reads. Over the
    sampling defaults the user's own --agent-kwarg wins; the sampling flags win over both. Other
    agents are not wired: they get no defaults, and refuse the flags.

    The thinking flags (scripts/common/thinking.py) add terminus-2's `reasoning_effort` kwarg and the
    chat-template kwargs in llm_kwargs' extra_body; they win over the user's own --agent-kwarg.
    """
    from scripts.common import sampling, thinking

    kwargs: Dict[str, str] = {}
    for kv in args.agent_kwarg:
        key, _, value = kv.partition("=")
        kwargs[key] = value
    try:
        explicit = {
            name: sampling.parse_value(name, getattr(args, name))
            for name in sampling.SAMPLERS
            if getattr(args, name) is not None
        }
        chosen = bool(explicit or args.sampling_profile or args.sampling_config)
        thinking_values = thinking.resolve(args.enable_thinking, args.reasoning_effort)
        if args.gold or args.agent != "terminus-2":
            if chosen or thinking_values:
                raise ValueError(
                    "the sampling and thinking flags apply to a model run with the terminus-2 agent; "
                    "for another agent pass --agent-kwarg yourself"
                )
            return list(args.agent_kwarg)
        values = sampling.resolve(
            "harbor",
            config=sampling.read_config(args.sampling_config),
            profile=args.sampling_profile,
            overrides=explicit,
            enable_thinking=args.enable_thinking,
            reasoning_effort=args.reasoning_effort,
        )
        if "temperature" in explicit:
            kwargs.pop("temperature", None)
        if "temperature" in values and "temperature" not in kwargs:
            kwargs["temperature"] = str(values["temperature"])
        llm_kwargs = json.loads(kwargs.get("llm_kwargs") or "{}")
        body = dict(llm_kwargs.get("extra_body") or {})
        for name in sampling.SAMPLERS[1:]:
            if name in explicit:
                body.pop(name, None)
            if name in values and (name in explicit or name not in body):
                body[name] = values[name]
    except (ValueError, json.JSONDecodeError) as exc:
        raise SystemExit(f"Error: {exc}") from exc
    if "reasoning_effort" in thinking_values:
        kwargs["reasoning_effort"] = thinking_values["reasoning_effort"]
    body = thinking.merge_extra_body(body, thinking_values)
    if body:
        kwargs["llm_kwargs"] = json.dumps({**llm_kwargs, "extra_body": body}, separators=(",", ":"))
    if chosen and (warning := sampling.greedy_warning(values)):
        print(warning, file=sys.stderr)
    return [f"{key}={value}" for key, value in kwargs.items()]


def harbor_command(args: argparse.Namespace, name: str, jobs_dir: Path) -> List[str]:
    spec = BENCHMARKS[name]
    cmd = [harbor_bin(), "run", "-o", str(jobs_dir), "--job-name", name, "-y", "-q"]
    if "adapter" in spec:
        dataset = download_dataset(*spec["hf_dataset"]) if "hf_dataset" in spec else None
        cmd += ["-p", str(generate_adapter_tasks(spec["adapter"], Path(args.work_dir), args.limit, args.task, dataset))]
    else:
        patches = task_patches(args, name)
        if patches:

            def patch(tasks: Path) -> None:
                for one in patches:
                    one(tasks)

            cmd += ["-p", str(patched_tasks(spec["dataset"], patch, Path(args.work_dir) / "tasks" / name))]
        else:
            cmd += ["-d", spec["dataset"]]
        for pattern in args.task:
            cmd += ["-i", pattern]
    if args.limit:
        cmd += ["-l", str(args.limit)]
    if args.gold:
        cmd += ["-a", "oracle"]
    else:
        cmd += ["-a", args.agent, "-m", f"openai/{args.model}"]
    cmd += ["-n", str(args.max_concurrency), "-k", str(args.attempts), "--timeout-multiplier", str(args.timeout_multiplier)]
    for kv in agent_kwargs(args):
        cmd += ["--ak", kv]
    cmd += ["--env", ENVIRONMENTS[args.sandbox]]
    return cmd


def harbor_env(args: argparse.Namespace) -> Dict[str, str]:
    env = dict(os.environ)
    # Our environments are imported by module path from this repo.
    env["PYTHONPATH"] = os.pathsep.join(filter(None, [str(REPO_ROOT), env.get("PYTHONPATH")]))
    if not args.gold:
        # litellm's openai provider (terminus-2, mini-swe-agent, ...): openai/<model> at this endpoint.
        env["OPENAI_BASE_URL"] = env["OPENAI_API_BASE"] = args.api_base_url
        env["OPENAI_API_KEY"] = os.environ.get("EVAL_MODEL_API_KEY", "")
    if args.sandbox == "docker" and platform.machine() in ("arm64", "aarch64"):
        # The task images are linux/amd64; Docker on an arm64 host would build for arm64 and
        # find no matching base image.
        env.setdefault("DOCKER_DEFAULT_PLATFORM", "linux/amd64")
    if args.sandbox == "opensandbox":
        env.setdefault("OPENSANDBOX_DOMAIN", OPENSANDBOX_KATA_DOMAIN)
        # Unique to this run: the cleanup after it must not touch another run's sandboxes. A
        # label the caller set (one per run of theirs) is kept.
        env.setdefault("OPENSANDBOX_RUN_LABEL", f"harbor-{uuid.uuid4().hex[:12]}")
    return env


def delete_leftover_sandboxes(env: Dict[str, str]) -> None:
    """A run that is stopped can leave sandboxes behind. Never fails the run: its scores stand, and
    a leftover ends at the sandbox's own timeout."""
    label = env["OPENSANDBOX_RUN_LABEL"]
    try:
        from scripts.harbor.opensandbox_environment import delete_run_sandboxes

        deleted = asyncio.run(
            asyncio.wait_for(delete_run_sandboxes(label, env["OPENSANDBOX_DOMAIN"], env["OPENSANDBOX_API_KEY"]), 120)
        )
    except Exception as exc:
        print(f"warning: could not delete sandboxes with sandbox-run={label}: {exc!r}", file=sys.stderr)
        return
    if deleted:
        print(f"Deleted {deleted} leftover sandboxes (sandbox-run={label})", flush=True)


def summarize_job(job_dir: Path, missing_reward_is_zero: bool = False) -> Dict[str, Any]:
    """Mean reward over the trials that were scored, and the trials that were not.

    Most verifiers write a single "reward"; some write several named metrics instead (e.g.
    SlopCodeBench's core_pass_rate, strict_pass_rate, erosion, ...): every metric's mean is
    reported under metrics, and mean_reward is the "reward" one where there is one.

    missing_reward_is_zero (the benchmark's own setting): a verifier that ran but wrote no reward
    file scores 0 instead of being an evaluation error; those trials are listed under
    no_reward_file."""
    rewards: List[float] = []
    metrics: Dict[str, List[float]] = {}
    errors: List[Dict[str, str]] = []
    no_reward_file: List[Dict[str, str]] = []
    for path in sorted(glob.glob(str(job_dir / "*" / "result.json"))):
        with open(path) as f:
            trial = json.load(f)
        verifier_rewards = (trial.get("verifier_result") or {}).get("rewards")
        if verifier_rewards:
            rewards.append(float(verifier_rewards.get("reward", 0.0)))
            for key, value in verifier_rewards.items():
                if isinstance(value, (int, float)):
                    metrics.setdefault(key, []).append(float(value))
            continue
        exc = trial.get("exception_info") or {}
        if missing_reward_is_zero and exc.get("exception_type") == "RewardFileNotFoundError":
            rewards.append(0.0)
            metrics.setdefault("reward", []).append(0.0)
            no_reward_file.append({"task": trial.get("task_name"), "trial": trial.get("trial_name")})
            continue
        errors.append(
            {
                "task": trial.get("task_name"),
                "trial": trial.get("trial_name"),
                "error": f"{exc.get('exception_type', 'no reward')}: {(exc.get('exception_message') or '')[:500]}",
            }
        )
    has_reward = "reward" in metrics
    summary = {
        "mean_reward": sum(rewards) / len(rewards) if rewards and has_reward else None,
        "metrics": {key: sum(values) / len(values) for key, values in sorted(metrics.items())},
        "n_trials": len(rewards) + len(errors),
        "n_scored": len(rewards),
        "evaluation_errors": errors,
    }
    if no_reward_file:
        summary["no_reward_file"] = no_reward_file
    # With --attempts > 1, Harbor's own pass@k over the attempts of each task.
    job_result = job_dir / "result.json"
    if job_result.exists():
        with open(job_result) as f:
            evals = ((json.load(f).get("stats") or {}).get("evals") or {}).values()
        pass_at_k = {k: v for ev in evals for k, v in (ev.get("pass_at_k") or {}).items()}
        if pass_at_k:
            summary["pass_at_k"] = pass_at_k
    return summary


def harbor_version() -> Optional[str]:
    try:
        from importlib.metadata import version

        return version("harbor")
    except Exception:
        return None


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    work_dir = Path(args.work_dir)
    jobs_dir = work_dir / "jobs"
    jobs_dir.mkdir(parents=True, exist_ok=True)
    env = harbor_env(args)
    results: Dict[str, Any] = {}
    summary = {
        "harbor_version": harbor_version(),
        "model": "oracle (reference solutions)" if args.gold else args.model,
        "agent": "oracle" if args.gold else args.agent,
        "api_base_url": None if args.gold else args.api_base_url,
        "sandbox": args.sandbox,
        # The server decides the runtime (Kata or not), so where the trials ran is part of the record.
        "sandbox_endpoint": env["OPENSANDBOX_DOMAIN"] if args.sandbox == "opensandbox" else None,
        "limit": args.limit,
        "attempts": args.attempts,
        "benchmarks": results,
    }
    # SIGTERM (e.g. a Slurm time limit): stop harbor, but keep the scores of the trials that
    # finished.
    stopped = False
    proc: Optional[subprocess.Popen] = None

    def stop(signum: int, frame: Any) -> None:
        nonlocal stopped
        stopped = True
        if proc is not None and proc.poll() is None:
            proc.terminate()

    signal.signal(signal.SIGTERM, stop)
    for name in args.benchmarks:
        if stopped:
            break
        cmd = harbor_command(args, name, jobs_dir)
        print("Running:", " ".join(cmd), flush=True)
        proc = subprocess.Popen(cmd, env=env, cwd=REPO_ROOT)
        if stopped:  # the signal came between the check above and the start
            proc.terminate()
        code = proc.wait()
        results[name] = {"dataset": BENCHMARKS[name].get("dataset") or f"adapter:{BENCHMARKS[name]['adapter']}"}
        patches = task_patches(args, name)
        if patches:
            results[name]["patched_with"] = ", ".join(one.__name__ for one in patches)
        if BENCHMARKS[name].get("agent_allowlist"):
            results[name]["agent_network"] = args.agent_network
        results[name].update(summarize_job(jobs_dir / name, BENCHMARKS[name].get("missing_reward_is_zero", False)))
        if stopped:
            results[name]["interrupted"] = True
        elif code != 0:
            results[name]["harbor_exit_code"] = code
        # After each benchmark, so a run that is stopped still leaves the finished ones' scores.
        with open(work_dir / "summary.json", "w") as f:
            json.dump(summary, f, indent=2)
    if args.sandbox == "opensandbox":
        delete_leftover_sandboxes(env)
    print(json.dumps(summary, indent=2))
    if stopped:
        print(f"Stopped: {work_dir}/summary.json has the trials that finished.", file=sys.stderr)
        return 128 + signal.SIGTERM
    failed = {n: r for n, r in results.items() if r["evaluation_errors"] or r.get("harbor_exit_code") or not r["n_trials"]}
    if failed:
        print(
            f"{', '.join(failed)}: trials without a verifier reward, no trials, or a failed harbor run (see "
            f"evaluation_errors in {work_dir}/summary.json): those scores are incomplete.",
            file=sys.stderr,
        )
        return 1
    return 0


