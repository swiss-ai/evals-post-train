"""Run agentic benchmarks through Harbor (see run_harbor_eval.sh).

Each benchmark is a Harbor dataset: a registry reference pinned below (a version, or a Harbor
Hub content digest), or, for Multi-SWE-bench, which has an adapter but no published dataset,
tasks generated locally by Harbor's adapter at the pinned Harbor version. One `harbor run` job
per benchmark, under <work-dir>/jobs/<benchmark>; then <work-dir>/summary.json with each
benchmark's mean reward and the trials that could not be scored.

A trial that ends without a verifier reward (the sandbox failed to start, a pod was
OOM-killed, the build replay failed, the cluster API dropped out) is an evaluation error,
not a wrong answer: it is listed under evaluation_errors and the run exits non-zero. A trial
whose agent failed or timed out still gets a reward from the verifier and counts normally.

--gold runs Harbor's oracle agent (each task's reference solution) instead of a model: a
check of the environments and verifiers, where every task should score 1 (some datasets
document tasks whose reference solution does not, e.g. flaky tests).
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import platform
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

REPO_ROOT = Path(__file__).resolve().parents[2]
HARBOR_VERSION = "0.25.0"
K8S_ENVIRONMENT = "scripts.harbor_runner.k8s_environment:K8sPodEnvironment"
# Harbor's Docker environment, with the network-allowlist sidecar built for DOCKER_DEFAULT_PLATFORM.
DOCKER_ENVIRONMENT = "scripts.harbor_runner.docker_environment:PlatformDockerEnvironment"

# Our benchmark names -> the Harbor dataset. Registry datasets are pinned: legacy-registry
# ones by version, Harbor Hub packages by content digest (what @latest resolved to when pinned).
